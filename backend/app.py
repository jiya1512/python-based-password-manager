from __future__ import annotations

import base64
import json
import os
import re
import secrets
import uuid
from contextlib import contextmanager
from datetime import timedelta
from pathlib import Path
from typing import Any, Iterator

from argon2 import PasswordHasher
from argon2.exceptions import VerificationError, VerifyMismatchError
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt
from flask import Flask, current_app, jsonify, render_template, request, session
from flask_session import Session
import psycopg
from psycopg.rows import dict_row
from werkzeug.middleware.proxy_fix import ProxyFix

USERNAME_RE = re.compile(r"^[A-Za-z0-9._-]{3,40}$")
MASTER_MIN_LENGTH = 12
KDF_SALT_BYTES = 16
GCM_NONCE_BYTES = 12
PASSWORD_HASHER = PasswordHasher(time_cost=3, memory_cost=65536, parallelism=2, hash_len=32, salt_len=16)


def _read_or_create_local_secret(instance_path: Path) -> str:
    """Convenience secret for local development. Production should set SECRET_KEY."""
    secret_file = instance_path / "dev_secret_key"
    if secret_file.exists():
        return secret_file.read_text(encoding="utf-8").strip()
    value = secrets.token_hex(32)
    secret_file.write_text(value, encoding="utf-8")
    try:
        secret_file.chmod(0o600)
    except OSError:
        pass
    return value


def create_app(test_config: dict[str, Any] | None = None) -> Flask:
    project_root = Path(__file__).resolve().parent.parent
    app = Flask(
        __name__,
        instance_relative_config=True,
        template_folder=str(project_root / "frontend" / "templates"),
        static_folder=str(project_root / "frontend" / "static"),
    )
    Path(app.instance_path).mkdir(parents=True, exist_ok=True)

    app.config.update(
        SECRET_KEY=os.environ.get("SECRET_KEY") or _read_or_create_local_secret(Path(app.instance_path)),
        DATABASE_URL=os.environ.get("DATABASE_URL", ""),
        SESSION_TYPE="filesystem",
        SESSION_FILE_DIR=os.environ.get("SESSION_FILE_DIR", str(Path(app.instance_path) / "server_sessions")),
        SESSION_PERMANENT=False,
        SESSION_USE_SIGNER=True,
        SESSION_COOKIE_HTTPONLY=True,
        SESSION_COOKIE_SAMESITE="Lax",
        SESSION_COOKIE_SECURE=os.environ.get("COOKIE_SECURE", "0") == "1",
        PERMANENT_SESSION_LIFETIME=timedelta(days=14),
        MAX_CONTENT_LENGTH=64 * 1024,
        JSON_SORT_KEYS=False,
    )
    if test_config:
        app.config.update(test_config)

    Path(app.config["SESSION_FILE_DIR"]).mkdir(parents=True, exist_ok=True)
    Session(app)

    # Only enable ProxyFix when deployed behind a trusted reverse proxy and configured accordingly.
    if os.environ.get("TRUST_PROXY", "0") == "1":
        app.wsgi_app = ProxyFix(app.wsgi_app, x_for=1, x_proto=1, x_host=1)

    @contextmanager
    def connect_db() -> Iterator[psycopg.Connection]:
        database_url = app.config["DATABASE_URL"]
        if not database_url:
            raise RuntimeError("DATABASE_URL must be set to a PostgreSQL connection string.")
        connection = psycopg.connect(database_url, row_factory=dict_row)
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def init_db() -> None:
        with connect_db() as db:
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT NOT NULL,
                    password_hash TEXT NOT NULL,
                    kdf_salt BYTEA NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            db.execute(
                """
                CREATE TABLE IF NOT EXISTS entries (
                    id TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    nonce BYTEA NOT NULL,
                    ciphertext BYTEA NOT NULL,
                    usage_count INTEGER NOT NULL DEFAULT 0 CHECK (usage_count >= 0),
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            db.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users (LOWER(username))")
            db.execute("CREATE INDEX IF NOT EXISTS idx_entries_user ON entries(user_id)")

    def csrf_token() -> str:
        token = session.get("csrf_token")
        if not token:
            token = secrets.token_urlsafe(32)
            session["csrf_token"] = token
        return token

    @app.before_request
    def protect_mutating_requests():
        if request.method in {"POST", "PUT", "PATCH", "DELETE"} and request.path.startswith("/api/"):
            expected = session.get("csrf_token", "")
            supplied = request.headers.get("X-CSRF-Token", "")
            if not expected or not supplied or not secrets.compare_digest(expected, supplied):
                return jsonify({"error": "Your session token expired. Refresh the page and try again."}), 403

    @app.after_request
    def security_headers(response):
        response.headers.setdefault("X-Content-Type-Options", "nosniff")
        response.headers.setdefault("Referrer-Policy", "no-referrer")
        response.headers.setdefault("X-Frame-Options", "DENY")
        response.headers.setdefault("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
        response.headers.setdefault(
            "Content-Security-Policy",
            "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; "
            "connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'",
        )
        response.headers.setdefault("Cache-Control", "no-store")
        return response

    def current_user_id() -> int | None:
        user_id = session.get("user_id")
        return int(user_id) if user_id is not None else None

    def get_vault_key() -> bytes | None:
        encoded = session.get("vault_key")
        if not encoded:
            return None
        try:
            key = base64.urlsafe_b64decode(encoded.encode("ascii"))
            return key if len(key) == 32 else None
        except (ValueError, UnicodeError):
            return None

    def require_auth():
        if current_user_id() is None or get_vault_key() is None:
            return jsonify({"error": "Please sign in again to unlock your vault."}), 401
        return None

    def derive_encryption_key(password: str, salt: bytes) -> bytes:
        # Scrypt is memory-hard; the separate Argon2id hash is used for login verification.
        kdf = Scrypt(salt=salt, length=32, n=2**15, r=8, p=1)
        return kdf.derive(password.encode("utf-8"))

    def encrypt_entry(user_id: int, entry_id: str, payload: dict[str, Any], key: bytes) -> tuple[bytes, bytes]:
        nonce = secrets.token_bytes(GCM_NONCE_BYTES)
        aad = f"keynest:v1:user:{user_id}:entry:{entry_id}".encode("utf-8")
        plaintext = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        ciphertext = AESGCM(key).encrypt(nonce, plaintext, aad)
        return nonce, ciphertext

    def decrypt_entry(user_id: int, entry_id: str, nonce: bytes, ciphertext: bytes, key: bytes) -> dict[str, Any]:
        aad = f"keynest:v1:user:{user_id}:entry:{entry_id}".encode("utf-8")
        plaintext = AESGCM(key).decrypt(nonce, ciphertext, aad)
        result = json.loads(plaintext.decode("utf-8"))
        if not isinstance(result, dict):
            raise ValueError("Invalid entry format")
        return result

    def entry_input(data: Any) -> dict[str, str] | None:
        if not isinstance(data, dict):
            return None
        site = str(data.get("site", "")).strip()
        url = str(data.get("url", "")).strip()
        login = str(data.get("login", "")).strip()
        password = str(data.get("password", ""))
        notes = str(data.get("notes", ""))
        if not site or len(site) > 100 or len(url) > 300 or len(login) > 150 or not password or len(password) > 1000 or len(notes) > 1000:
            return None
        return {"site": site, "url": url, "login": login, "password": password, "notes": notes}

    def entry_response(row: dict[str, Any], user_id: int, key: bytes) -> dict[str, Any]:
        try:
            payload = decrypt_entry(user_id, row["id"], row["nonce"], row["ciphertext"], key)
        except Exception as exc:
            current_app.logger.error("Vault entry could not be decrypted (entry id %s): %s", row["id"], type(exc).__name__)
            raise ValueError("A vault entry could not be decrypted. Check the master password and database integrity.") from exc
        return {
            "id": row["id"],
            **payload,
            "usageCount": row["usage_count"],
            "updatedAt": row["updated_at"].isoformat(),
        }

    @app.get("/")
    def index():
        return render_template("index.html", csrf_token=csrf_token())

    @app.get("/api/session")
    def api_session():
        user_id = current_user_id()
        username = session.get("username")
        return jsonify({"authenticated": bool(user_id and get_vault_key()), "username": username, "csrf": csrf_token()})

    @app.post("/api/register")
    def register():
        data = request.get_json(silent=True) or {}
        username = str(data.get("username", "")).strip()
        password = str(data.get("masterPassword", ""))
        confirm = str(data.get("confirmPassword", ""))
        if not USERNAME_RE.fullmatch(username):
            return jsonify({"error": "Username must be 3–40 characters using letters, numbers, dots, underscores, or hyphens."}), 400
        if len(password) < MASTER_MIN_LENGTH or len(password) > 1024:
            return jsonify({"error": "Master password must be at least 12 characters."}), 400
        if password != confirm:
            return jsonify({"error": "The master passwords do not match."}), 400

        salt = secrets.token_bytes(KDF_SALT_BYTES)
        password_hash = PASSWORD_HASHER.hash(password)
        try:
            with connect_db() as db:
                cursor = db.execute(
                    "INSERT INTO users (username, password_hash, kdf_salt) VALUES (%s, %s, %s) RETURNING id",
                    (username, password_hash, salt),
                )
                user_id = int(cursor.fetchone()["id"])
        except psycopg.IntegrityError:
            return jsonify({"error": "That username is already registered. Try logging in instead."}), 409

        key = derive_encryption_key(password, salt)
        session.clear()
        session["user_id"] = user_id
        session["username"] = username
        session["vault_key"] = base64.urlsafe_b64encode(key).decode("ascii")
        session["csrf_token"] = secrets.token_urlsafe(32)
        return jsonify({"ok": True, "username": username, "csrf": session["csrf_token"]}), 201

    @app.post("/api/login")
    def login():
        data = request.get_json(silent=True) or {}
        username = str(data.get("username", "")).strip()
        password = str(data.get("masterPassword", ""))
        remember = bool(data.get("remember", False))
        with connect_db() as db:
            user = db.execute("SELECT * FROM users WHERE LOWER(username) = LOWER(%s)", (username,)).fetchone()
        if not user:
            return jsonify({"error": "Invalid username or master password."}), 401
        try:
            PASSWORD_HASHER.verify(user["password_hash"], password)
        except (VerificationError, VerifyMismatchError, ValueError):
            return jsonify({"error": "Invalid username or master password."}), 401

        key = derive_encryption_key(password, user["kdf_salt"])
        session.clear()
        session["user_id"] = int(user["id"])
        session["username"] = user["username"]
        session["vault_key"] = base64.urlsafe_b64encode(key).decode("ascii")
        session["csrf_token"] = secrets.token_urlsafe(32)
        session.permanent = remember
        return jsonify({"ok": True, "username": user["username"], "csrf": session["csrf_token"], "remembered": remember})

    @app.post("/api/logout")
    def logout():
        session.clear()
        token = secrets.token_urlsafe(32)
        session["csrf_token"] = token
        return jsonify({"ok": True, "csrf": token})

    @app.get("/api/entries")
    def list_entries():
        auth_error = require_auth()
        if auth_error:
            return auth_error
        user_id, key = current_user_id(), get_vault_key()
        with connect_db() as db:
            rows = db.execute("SELECT * FROM entries WHERE user_id = %s ORDER BY updated_at DESC", (user_id,)).fetchall()
        try:
            return jsonify({"entries": [entry_response(row, user_id, key) for row in rows]})
        except ValueError as exc:
            return jsonify({"error": str(exc)}), 500

    @app.post("/api/entries")
    def create_entry():
        auth_error = require_auth()
        if auth_error:
            return auth_error
        payload = entry_input(request.get_json(silent=True))
        if payload is None:
            return jsonify({"error": "Please provide a site name and password. Check the field length limits."}), 400
        user_id, key = current_user_id(), get_vault_key()
        entry_id = str(uuid.uuid4())
        nonce, ciphertext = encrypt_entry(user_id, entry_id, payload, key)
        with connect_db() as db:
            row = db.execute(
                "INSERT INTO entries (id, user_id, nonce, ciphertext) VALUES (%s, %s, %s, %s) RETURNING *",
                (entry_id, user_id, nonce, ciphertext),
            ).fetchone()
        return jsonify({"entry": entry_response(row, user_id, key)}), 201

    @app.put("/api/entries/<entry_id>")
    def update_entry(entry_id: str):
        auth_error = require_auth()
        if auth_error:
            return auth_error
        payload = entry_input(request.get_json(silent=True))
        if payload is None:
            return jsonify({"error": "Please provide a site name and password. Check the field length limits."}), 400
        user_id, key = current_user_id(), get_vault_key()
        nonce, ciphertext = encrypt_entry(user_id, entry_id, payload, key)
        with connect_db() as db:
            cursor = db.execute(
                "UPDATE entries SET nonce = %s, ciphertext = %s, updated_at = CURRENT_TIMESTAMP WHERE id = %s AND user_id = %s",
                (nonce, ciphertext, entry_id, user_id),
            )
            if cursor.rowcount == 0:
                return jsonify({"error": "Entry not found."}), 404
            row = db.execute("SELECT * FROM entries WHERE id = %s AND user_id = %s", (entry_id, user_id)).fetchone()
        return jsonify({"entry": entry_response(row, user_id, key)})

    @app.delete("/api/entries/<entry_id>")
    def delete_entry(entry_id: str):
        auth_error = require_auth()
        if auth_error:
            return auth_error
        with connect_db() as db:
            cursor = db.execute("DELETE FROM entries WHERE id = %s AND user_id = %s", (entry_id, current_user_id()))
        if cursor.rowcount == 0:
            return jsonify({"error": "Entry not found."}), 404
        return jsonify({"ok": True})

    @app.post("/api/entries/<entry_id>/used")
    def mark_used(entry_id: str):
        auth_error = require_auth()
        if auth_error:
            return auth_error
        with connect_db() as db:
            cursor = db.execute(
                "UPDATE entries SET usage_count = usage_count + 1, updated_at = CURRENT_TIMESTAMP WHERE id = %s AND user_id = %s",
                (entry_id, current_user_id()),
            )
            if cursor.rowcount == 0:
                return jsonify({"error": "Entry not found."}), 404
            row = db.execute("SELECT * FROM entries WHERE id = %s AND user_id = %s", (entry_id, current_user_id())).fetchone()
        return jsonify({"entry": entry_response(row, current_user_id(), get_vault_key())})

    @app.errorhandler(413)
    def request_too_large(_error):
        return jsonify({"error": "Request is too large."}), 413

    init_db()
    return app


app = create_app()

if __name__ == "__main__":
    # Development server only. Use a production WSGI server for deployment.
    app.run(host="127.0.0.1", port=int(os.environ.get("PORT", "5000")), debug=False)
